#!/usr/bin/env python3
"""Prepare the user's artwork for the 400x240 top screen and 3DS HOME assets.
All crops preserve aspect ratio; no generated replacement artwork is used.
"""
from pathlib import Path
from PIL import Image,ImageDraw,ImageOps
import re,wave
root=Path(__file__).resolve().parents[1]
source=Image.open(root/'assets/home-source.jpg').convert('RGB')
home=ImageOps.fit(source,(400,240),Image.Resampling.LANCZOS,centering=(.5,.35))
home.save(root/'assets/home.png',optimize=True)
# A tighter square keeps Emry's face and sword legible at the HOME icon size.
icon=source.crop((335,95,1215,975)).resize((48,48),Image.Resampling.LANCZOS)
icon.save(root/'assets/icon.png')
icon.resize((24,24),Image.Resampling.LANCZOS).save(root/'assets/icon-small.png')
values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in home.getdata()]
lines=[','.join('0x%04x'%v for v in values[i:i+16]) for i in range(0,len(values),16)]
(root/'include/home_art.hpp').write_text('// Generated by tools/make_assets.py from the supplied artwork. RGB565, row-major.\n#pragma once\n#include <cstdint>\nnamespace deck {\ninline constexpr uint16_t homeArtPixels[400*240]={\n'+',\n'.join(lines)+'\n};\n}\n')
s=(root/'include/medieval_atlas.hpp').read_text()
widths=list(map(int,re.search(r'widths\[95\]=\{([^}]+)',s)[1].split(',')))
rows=[[int(v,16) for v in t.split(',')] for t in re.findall(r'\{(0x[^{}]+)\}',s)]
def text(image,value,x,y,scale=1,color='#f1e5c5'):
 d=ImageDraw.Draw(image)
 for ch in value:
  i=ord(ch)-32
  if 0<=i<95:
   for ry,row in enumerate(rows[i]):
    for rx in range(widths[i]):
     if row>>rx&1:d.rectangle((x+rx*scale,y+ry*scale,x+(rx+1)*scale-1,y+(ry+1)*scale-1),fill=color)
   x+=(widths[i]+1)*scale
banner=ImageOps.fit(source,(256,128),Image.Resampling.LANCZOS,centering=(.5,.2))
word='LIFELOCH';width=sum(widths[ord(c)-32]+1 for c in word)
x=(256-width)//2
text(banner,word,x+1,10,color='#142027');text(banner,word,x,9)
banner.save(root/'assets/banner.png')
with wave.open(str(root/'assets/silence.wav'),'wb') as audio:
 audio.setnchannels(1);audio.setsampwidth(2);audio.setframerate(32000);audio.writeframes(bytes(6400))
old=root/'assets/banner.bnr'
if old.exists():old.unlink()
print('Prepared home artwork 400x240, HOME icons 48/24px, banner 256x128 and native RGB565 pixels.')
